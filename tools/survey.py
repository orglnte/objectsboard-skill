#!/usr/bin/env python3
"""Which folders of a repo hold the code to analyze: the setup step before a trace.

    survey.py [--root .]

Run it from the repo root. Prints the folders as a tree, each `analyze` or
`skip` with its reason, and the `exclude` list to save: the saved entries and
those verdicts. Reads .objectsboard.json and writes nothing.

A sure verdict comes from what a folder is: an environment, a folder with no
Python, a hidden folder, the tests. `?` marks a guess, from what a folder only
looks like: its own git repository, a name such as `vendor` or `docs`, files
that say they are generated, or no file outside importing it. A `?` folder is
the user's to decide. A saved decision (`exclude`, `analyze` in
.objectsboard.json) is sure, except that an environment is always skipped.
Folders under a skipped one are not listed: the decision covers them.

Imports are matched by name: a folder counts as imported when an import names
it or one of the modules directly in it, even if that import means another
package with the same name.
"""
import argparse, ast, json, re
from pathlib import Path

from pyfiles import is_env, py_files
from trace_objects import load_prefs

TESTS = {"test", "tests", "testing"}
NAMED = {
    "vendored code": {"vendor", "vendored", "third_party", "thirdparty", "external", "extern", "deps"},
    "build output": {"build", "dist", "out", "target", "generated", "gen"},
    "documentation or examples": {"docs", "doc", "examples", "example", "samples", "sample", "demo", "demos",
                                  "notebooks", "tutorials"},
    "tooling": {"scripts", "benchmarks", "bench", "migrations", "ci"},
    "old or temporary code": {"legacy", "old", "deprecated", "archive", "tmp", "temp"},
}
GENERATED = re.compile(r"generated by|auto-?generated|do not edit", re.I)


def imported_names(files):
    """{name: files importing it}, one entry per dotted part of each import."""
    names = {}
    for p in files:
        try:
            tree = ast.parse(p.read_text())
        except (SyntaxError, UnicodeDecodeError, ValueError):
            continue
        for n in ast.walk(tree):
            if isinstance(n, ast.Import):
                parts = {x for a in n.names for x in a.name.split(".")}
            elif isinstance(n, ast.ImportFrom):
                parts = set((n.module or "").split(".")) | {a.name for a in n.names}
            else:
                continue
            for x in parts:
                names.setdefault(x, set()).add(p)
    return names


def only_tests(files):
    """Whether every file is a test file; a package's `__init__.py` says nothing either way."""
    named = [p.name for p in files if p.name != "__init__.py"]
    return bool(named) and all(n.startswith("test_") or n.endswith("_test.py") or n == "conftest.py" for n in named)


def generated(files):
    heads = ["\n".join(p.read_text(errors="replace").splitlines()[:5]) for p in files]
    heads = [h for h in heads if h.strip()]
    return bool(heads) and all(GENERATED.search(h) for h in heads)


def verdict(d, under, names, exclude, analyze):
    """(verdict, why, sure) for folder d, holding the files under."""
    if is_env(d):
        return "skip", "Python environment", True
    if d in exclude:
        return "skip", "saved in exclude", True
    if d in analyze:
        return "analyze", "saved in analyze", True
    if not under:
        return "skip", "no Python files", True
    if d.name.startswith("."):
        return "skip", "hidden folder", True
    if d.name in TESTS or only_tests(under):
        return "skip", "tests: they drive the trace, they are not drawn", True
    if (d / ".git").exists():
        return "skip", "its own git repository", False
    for kind, words in NAMED.items():
        if d.name in words:
            return "skip", f"named like {kind}", False
    if generated(under):
        return "skip", "its files say they are generated", False
    own = {d.name} | {p.stem for p in under if p.parent == d and p.stem != "__init__"}
    importers = set().union(*(names.get(x, set()) for x in own)) - set(under)
    if not importers:
        return "skip", "no file outside imports it", False
    return "analyze", f"imported by {len(importers)} file(s)", True


def survey(root=".", prefs=None):
    """The folder tree: nested {"path", "name", "verdict", "why", "sure",
    "python", "children"}, with the root as its top, which also holds the
    saved `exclude` entries."""
    prefs = prefs or {}
    exclude, analyze = {Path(e) for e in prefs.get("exclude", [])}, {Path(e) for e in prefs.get("analyze", [])}
    files = py_files(root)
    names = imported_names(files)

    def visit(d):
        under = [p for p in files if d in p.parents]
        v, why, sure = verdict(d, under, names, exclude, analyze)
        node = {"path": str(d), "name": d.name, "verdict": v, "why": why, "sure": sure, "python": bool(under),
                "children": []}
        if v == "analyze":
            node["children"] = walk(d)
        return node

    def walk(d):
        return [visit(c) for c in sorted(d.iterdir()) if c.is_dir() and c.name != "__pycache__"]

    top = Path(root)
    return {"path": str(top), "name": top.resolve().name, "verdict": "analyze", "why": "the root", "sure": True,
            "python": bool(files), "children": walk(top), "saved": list(prefs.get("exclude", []))}


def nodes(tree):
    yield tree
    for c in tree["children"]:
        yield from nodes(c)


def to_exclude(tree):
    """The list to save: every saved entry, and the folders the verdicts leave
    out. An environment and a folder with no Python need no entry of their own:
    no scan reads them."""
    return sorted({n["path"] for n in nodes(tree) if n["verdict"] == "skip" and n["python"]} | set(tree["saved"]))


def rows(node, prefix=""):
    for i, c in enumerate(node["children"]):
        last = i == len(node["children"]) - 1
        yield prefix + ("└── " if last else "├── ") + c["name"] + "/", c
        yield from rows(c, prefix + ("    " if last else "│   "))


def render(tree):
    table = [(tree["name"] + "/", tree), *rows(tree)]
    width = max(len(left) for left, _ in table)
    out = [f"{left:<{width}}  {('' if n['sure'] else '? ') + n['verdict']:<9}  {n['why']}" for left, n in table]
    unsure = sum(not n["sure"] for n in nodes(tree))
    out += ["", f"layout unclear: {unsure} folder(s) to decide, marked ?" if unsure else "layout clear",
            "exclude: " + json.dumps(to_exclude(tree))]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=".")
    print(render(survey(ap.parse_args().root, load_prefs())))


if __name__ == "__main__":
    main()
